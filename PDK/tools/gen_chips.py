#!/usr/bin/env python3
"""Generates <chip>_regs.sinc (io register definitions) and <chip>_attach.sinc (attach of the io field)
from tools/chips.json.  Unnamed io addresses become io_XX so that every encoding decodes.
usage: gen_chips.py <outdir>"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
chips = json.load(open(os.path.join(HERE, "chips.json")))
outdir = sys.argv[1]
for chip, c in sorted(chips.items()):
    n = 1 << (c["width"] - 8)          # 13 -> 32, 14 -> 64, 15 -> 128, 16 -> 256 (pdk16 uses 6 bits only)
    n = {13: 32, 14: 64, 15: 128, 16: 64}[c["width"]]
    names = []
    regs = []
    for a in range(n):
        nm = c["io"].get(str(a))
        if nm is None:
            nm = "io_%02x" % a
        names.append(nm)
        if a not in (0, 2):
            regs.append((a, nm))
    with open(os.path.join(outdir, chip.lower() + "_regs.sinc"), "w") as f:
        f.write(f"# GENERATED by tools/gen_chips.py from tools/chips.json. Do not edit.\n# I/O registers of the {chip}\n")
        for a, nm in regs:
            f.write(f"define register offset=0x{0x100 + a:03x} size=1 [ {nm} ];\n")
    with open(os.path.join(outdir, chip.lower() + "_attach.sinc"), "w") as f:
        f.write("# GENERATED by tools/gen_chips.py from tools/chips.json. Do not edit.\nattach variables [ ioa ] [\n")
        for i in range(0, n, 8):
            f.write("\t" + " ".join(names[i:i + 8]) + "\n")
        f.write("];\n")
